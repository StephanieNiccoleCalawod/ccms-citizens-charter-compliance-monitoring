import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { RECEIPT_MAX_BYTES } from '../../../migrations/1794900200000-Cc045TransactionReceipts.js';

// =================================================================================================================
// CC045 private receipt storage: the one small contract every provider implements.
//
//   put(key, bytes, contentType)   store the object privately; resolve only once it is durably written
//   get(key)                       -> Buffer, or null when there is no such object
//   delete(key)                    remove it; deleting a missing object is not an error
// Keys are generated by the server (receipts/<uuid>/<uuid>); a provider never returns a URL to the browser. Every read goes
// through GET /api/transactions/:id/receipt/image, which re-checks the session and the office on each request.
//
// RECEIPT_STORAGE selects the provider:
//   vercel-blob   private Vercel Blob (BE Dev 1 confirmed 11/13/2026 for the hosted development demo, Hobby plan, dummy receipts
//                 only). Server-side @vercel/blob put/get/del with access 'private'. Authentication is the SDK's own default: the
//                 Vercel OIDC token of the running function together with BLOB_STORE_ID (a connected store); a
//                 BLOB_READ_WRITE_TOKEN is used only when no OIDC token is available. Neither is ever read or returned here.
//                 Without BLOB_STORE_ID or BLOB_READ_WRITE_TOKEN the adapter is "not connected" and answers 503.
//   memory        tests and a single local process only (lost on restart)
//   filesystem    local development: RECEIPT_STORAGE_DIR (outside the web root; never served directly)
//   (unset)       no storage: upload and image reads answer 503; metadata reads and deletes of existing rows still work.
// memory and filesystem are refused when VERCEL is set (a hosted deployment), so a demo never keeps receipts on a server disk.
// Real receipts are outside the demo and need the approved privacy notice first.
// =================================================================================================================

export class StorageUnavailableError extends Error {
  constructor(message = 'Receipt storage is not available') {
    super(message);
    this.name = 'StorageUnavailableError';
  }
}

export function createMemoryStorage() {
  const objects = new Map();
  return {
    kind: 'memory',
    objects,
    async put(key, bytes) { objects.set(key, Buffer.from(bytes)); },
    async get(key) { return objects.has(key) ? Buffer.from(objects.get(key)) : null; },
    async delete(key) { objects.delete(key); },
  };
}

export function createFilesystemStorage(root) {
  const base = resolve(root);
  const pathOf = (key) => {
    const path = resolve(join(base, key));
    if (!path.startsWith(base + sep)) throw new StorageUnavailableError('Invalid storage key');
    return path;
  };
  return {
    kind: 'filesystem',
    async put(key, bytes) {
      const path = pathOf(key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, bytes, { flag: 'wx' });
    },
    async get(key) {
      try {
        return await readFile(pathOf(key));
      } catch (err) {
        if (err?.code === 'ENOENT') return null;
        throw err;
      }
    },
    async delete(key) { await rm(pathOf(key), { force: true }); },
  };
}

/** Reads a web ReadableStream into one Buffer, refusing more than `max` bytes (a stored receipt is never larger). */
async function readAll(stream, max) {
  const reader = stream.getReader();
  const chunks = [];
  let size = 0;
  try {
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > max) {
        await reader.cancel().catch(() => {});
        throw new StorageUnavailableError('The stored object is larger than a receipt can be');
      }
      chunks.push(Buffer.from(value));
    }
  } finally {
    reader.releaseLock();
  }
  return Buffer.concat(chunks);
}

/**
 * Private Vercel Blob. `sdk` is { put, get, del } from @vercel/blob (loaded on first use); tests pass a double so no hosted quota is
 * used. Every SDK failure surfaces as StorageUnavailableError with the SDK error's NAME only: messages and URLs never travel
 * further (they could carry the store host), and the put result (which holds the blob URL) is discarded.
 */
export function createVercelBlobStorage({ sdk = null } = {}) {
  let loaded = sdk;
  const client = async () => (loaded ??= await import('@vercel/blob'));
  const failed = (err) => new StorageUnavailableError(`Private Blob ${err?.name ?? 'Error'}`);
  return {
    kind: 'vercel-blob',
    async put(key, bytes, contentType) {
      try {
        // Exact pathname (no random suffix: the key is already a fresh uuid), never overwrite, private access.
        await (await client()).put(key, bytes, { access: 'private', contentType, addRandomSuffix: false, allowOverwrite: false });
      } catch (err) {
        throw failed(err);
      }
    },
    async get(key) {
      let result;
      try {
        result = await (await client()).get(key, { access: 'private' });
      } catch (err) {
        if (err?.name === 'BlobNotFoundError') return null;
        throw failed(err);
      }
      if (!result) return null;
      if (result.statusCode !== 200 || !result.stream) throw new StorageUnavailableError('Private Blob returned no content');
      return readAll(result.stream, RECEIPT_MAX_BYTES);
    },
    async delete(key) {
      try {
        await (await client()).del(key);
      } catch (err) {
        if (err?.name === 'BlobNotFoundError') return;
        throw failed(err);
      }
    },
  };
}

function unavailableStorage(reason) {
  const fail = async () => { throw new StorageUnavailableError(reason); };
  return { kind: 'none', reason, put: fail, get: fail, delete: fail };
}

let override = null;
let fromEnv = null;
/** Tests replace the storage; null goes back to the environment's choice. */
export function setReceiptStorage(storage) {
  override = storage ?? null;
  fromEnv = null;
}

/** True when a Blob store is connected to this deployment (the SDK finds its credentials from these). */
export const blobStoreConnected = (env = process.env) => Boolean(String(env.BLOB_STORE_ID ?? '').trim() || String(env.BLOB_READ_WRITE_TOKEN ?? '').trim());

export function storageFromEnv(env = process.env, { blobSdk = null } = {}) {
  const kind = String(env.RECEIPT_STORAGE ?? '').trim().toLowerCase();
  const hosted = Boolean(env.VERCEL);
  if (kind === 'vercel-blob') {
    return blobStoreConnected(env) ? createVercelBlobStorage({ sdk: blobSdk }) : unavailableStorage('RECEIPT_STORAGE=vercel-blob but no Blob store is connected');
  }
  if (kind === 'memory' && !hosted) return createMemoryStorage();
  if (kind === 'filesystem' && !hosted && env.RECEIPT_STORAGE_DIR) return createFilesystemStorage(env.RECEIPT_STORAGE_DIR);
  return unavailableStorage(kind ? `RECEIPT_STORAGE=${kind} is not usable here` : 'RECEIPT_STORAGE is not configured');
}

export function receiptStorage() {
  if (override) return override;
  fromEnv ??= storageFromEnv();
  return fromEnv;
}

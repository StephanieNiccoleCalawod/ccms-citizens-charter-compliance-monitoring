import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { isTermChoice, parseTerms, periodParams, termChoices, termPeriodText } from '../../src/lib/ui/term-period.js';
import { buildGenerateBody, periodSentence } from '../../src/lib/ui/reports.js';

const terms = parseTerms({ items: [
  { term_code: '2026-1S', term_name: '1st Semester', academic_year: '2026-2027', start_date: '2026-08-17', end_date: '2026-12-02' },
  { term_code: '2026-2S', term_name: '2nd Semester', academic_year: '2026-2027', start_date: '2027-01-05', end_date: '2027-05-28' },
  { term_code: 'x', term_name: 'No dates' },
] });

describe('S8-64 term and school-year choices', () => {
  it('lists terms with dates, newest first, and one school year', () => {
    assert.equal(terms.length, 2);
    const c = termChoices(terms);
    assert.equal(c.terms[0].value, 'term:2026-2S');
    assert.deepEqual(c.years, [{ value: 'year:2026-2027', label: 'School Year 2026-2027' }]);
  });
  it('turns a choice into the right query part', () => {
    assert.deepEqual(periodParams('term:2026-1S'), { term: '2026-1S' });
    assert.deepEqual(periodParams('year:2026-2027'), { school_year: '2026-2027' });
    assert.deepEqual(periodParams('monthly'), { period: 'monthly' });
    assert.equal(isTermChoice('monthly'), false);
  });
  it('writes the period out with dates', () => {
    assert.equal(termPeriodText('term:2026-1S', terms), '1st Semester, School Year 2026–2027 (August 17 – December 2, 2026)');
    assert.equal(termPeriodText('year:2026-2027', terms), 'School Year 2026–2027 (August 17, 2026 – May 28, 2027)');
    assert.equal(termPeriodText('monthly', terms), null);
  });
  it('no terms: nothing to choose (the selector greys out)', () => {
    const c = termChoices(parseTerms({ items: [] }));
    assert.equal(c.terms.length + c.years.length, 0);
  });
  it('a report generated by term sends the term, and its sheet shows the label', () => {
    assert.deepEqual(buildGenerateBody({ officeId: 'o', periodType: 'term:2026-1S' }), { officeId: 'o', term: '2026-1S' });
    assert.deepEqual(buildGenerateBody({ officeId: 'o', periodType: 'year:2026-2027' }), { officeId: 'o', schoolYear: '2026-2027' });
    const r = { period_type: 'custom', from: '2026-08-17', to: '2026-12-02', figures: { period_label: '1st Semester, School Year 2026-2027' } };
    assert.equal(periodSentence(r), '1st Semester, School Year 2026–2027 (August 17 – December 2, 2026)');
  });
});
